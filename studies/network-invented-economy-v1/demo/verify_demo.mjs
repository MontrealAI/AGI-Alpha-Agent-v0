class Element {
  constructor(tag, attrs) {
    this.tag = tag;
    this.attrs = attrs;
    this.id = attrs.id;
    this.dataset = {};
    for (const [key, value] of Object.entries(attrs)) {
      if (key.startsWith('data-')) {
        this.dataset[key.slice(5).replace(/-([a-z])/g, (_, c) => c.toUpperCase())] = value;
      }
    }
    this._value = attrs.value ?? '';
    this.hidden = Object.hasOwn(attrs, 'hidden');
    this.disabled = false;
    this._html = '';
    this.textContent = '';
    this.max = attrs.max;
    this.min = attrs.min;
    this.handlers = {};
    this.classes = new Set((attrs.class ?? '').split(' '));
    this.classList = {toggle: (name, on) => on ? this.classes.add(name) : this.classes.delete(name)};
  }

  set innerHTML(value) {
    this._html = value;
    if (this.tag === 'select') {
      this.options = [...value.matchAll(/<option value="([^"]*)"/g)].map(match => decoded(match[1]));
      this._value = this.options[0] ?? '';
    }
  }

  get innerHTML() { return this._html; }

  set value(value) {
    this._value = String(value);
    if (this.attrs.type === 'range') {
      this._value = String(Math.min(Number(this.max), Math.max(Number(this.min), Number(value))));
    }
  }

  get value() { return this._value; }
  setAttribute(key, value) { this.attrs[key] = String(value); }
  getAttribute(key) { return this.attrs[key]; }
  addEventListener(key, handler) { this.handlers[key] = handler; }
  scrollIntoView() {}
  focus() { document.activeElement = this; }
  click() { this.onclick?.(); }
}

// Script template literals can contain markup. Exclude script CONTENT before
// parsing the static element inventory, otherwise dynamic IDs become fake nodes.
const markup = html.replace(/(<script\b[^>]*>)[\s\S]*?<\/script>/gi, '$1</script>');
for (const match of markup.matchAll(/<([a-z][a-z0-9-]*)(\s[^>]*?)?>/gi)) {
  const attrs = {};
  for (const attr of (match[2] ?? '').matchAll(/([\w:-]+)(?:="([^"]*)")?/g)) {
    attrs[attr[1]] = decoded(attr[2] ?? '');
  }
  const node = new Element(match[1].toLowerCase(), attrs);
  nodes.push(node);
  if (node.id) {
    assert(!ids.has(node.id), `duplicate static ID: ${node.id}`);
    ids.set(node.id, node);
  }
}

const dataMatch = html.match(/<script type="application\/json" id="study-data">([\s\S]*?)<\/script>/);
assert(dataMatch, 'embedded study-data JSON is required');
ids.get('study-data').textContent = dataMatch[1];
for (const match of html.matchAll(/<select\b[^>]*id="([^"]+)"[^>]*>([\s\S]*?)<\/select>/g)) {
  const first = match[2].match(/<option(?:\s+selected)?>([^<]*)<\/option>/);
  const selected = match[2].match(/<option\s+selected>([^<]*)<\/option>/);
  ids.get(match[1])._value = selected?.[1] ?? first?.[1] ?? '';
}

const document = {
  getElementById(id) {
    assert(ids.has(id), `missing static ID: ${id}`);
    return ids.get(id);
  },
  querySelectorAll(selector) {
    if (selector === '[data-panel]') return nodes.filter(node => node.dataset.panel);
    if (selector === '[data-i18n]') return nodes.filter(node => node.dataset.i18n);
    if (selector === '[data-i18n-html]') return nodes.filter(node => node.dataset.i18nHtml);
    if (selector === '.panel') return nodes.filter(node => node.classes.has('panel'));
    return [];
  },
  querySelector(selector) {
    return selector === 'nav.tabs' ? nodes.find(node => node.tag === 'nav' && node.classes.has('tabs')) : null;
  },
  documentElement: {lang: 'en'},
  createElement: tag => new Element(tag, {}),
  activeElement: null,
};

