"""Restore absent recorded data exactly from frozen local implementations.

This is replay-only packaging. It uses no network, models, keys or new choices.
All generated bytes are verified before any file is installed. Existing evidence
is never overwritten. The complete downloadable archive already contains the data.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re
import shutil
import subprocess
import sys
import tempfile
import time
from typing import Any
import zlib

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "packaging/public_data_manifest.json"
TARGETS = (
    "economics/results/development.json",
    "economics/results/confirmation.json",
    "economics/results/events.jsonl.gz",
    "economics/value_results/confirmation.json",
    "economics/value_results/events.jsonl.gz",
    "economics/prescreen_results/prescreen_confirmation.json",
    "opportunity/arrangement/results/conditional_frontier.json",
)
SOURCE_FILES = (
    "economics/run_economics.py",
    "economics/protocol.json",
    "integration/admission.py",
    "economics/results/FREEZE.json",
    "economics/results/pilot_input.json",
    "economics/results/summary.json",
    "economics/results/CONFIRMATION_COMPLETE.json",
    "economics/value_controller.py",
    "economics/value_protocol.json",
    "economics/value_results/VALUE_FREEZE.json",
    "economics/value_results/summary.json",
    "economics/value_results/VALUE_CONFIRMATION_COMPLETE.json",
    "economics/prescreen_experiment.py",
    "economics/prescreen_results/PRESCREEN_FREEZE.json",
    "economics/prescreen_results/prescreen_summary.json",
    "opportunity/arrangement/checker.py",
    "opportunity/arrangement/PROTOCOL.json",
    "opportunity/arrangement/results/FREEZE.json",
    "opportunity/arrangement/results/reference_selection.json",
)
sys.dont_write_bytecode = True
os.environ["PYTHONDONTWRITEBYTECODE"] = "1"


def require(condition: bool, message: str) -> None:
    """Fail closed independently of Python optimization."""
    if not condition:
        raise ValueError(message)


def sha(path: Path) -> str:
    """Hash large artifacts without reading them entirely into memory."""
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def safe_path(root: Path, relative: str) -> Path:
    """Reject absolute, traversal, ambiguous or symlinked manifest paths."""
    require(isinstance(relative, str) and bool(relative), "Path must be a nonempty string")
    value = PurePosixPath(relative)
    require(not value.is_absolute() and "\\" not in relative and ":" not in relative, "Unsafe manifest path")
    require(str(value) == relative and all(p not in (".", "..") for p in value.parts), "Unsafe manifest path")
    result = root
    for part in value.parts:
        result = result / part
        require(not result.is_symlink(), "Symlinked source or destination refused: " + relative)
    require(result.resolve().is_relative_to(root.resolve()), "Path escapes study root")
    return result


def matches(path: Path, record: dict[str, Any]) -> bool:
    """Check an ordinary file against its exact recorded length and digest."""
    return (
        path.is_file()
        and not path.is_symlink()
        and path.stat().st_size == record["bytes"]
        and sha(path) == record["sha256"]
    )


def verify_manifest() -> tuple[dict[str, Any], dict[str, dict[str, Any]], list[str]]:
    """Verify paths, source commitments and all already present target data."""
    require(not MANIFEST.is_symlink(), "Symlinked data manifest refused")
    data = json.loads(MANIFEST.read_text(encoding="utf-8"))
    require(data.get("schema") == "compact-public-recorded-data/v1", "Unsupported data manifest")
    records = data["omitted_from_compact_source"]
    for record in records:
        safe_path(ROOT, record["path"])
        require(type(record["bytes"]) is int and record["bytes"] > 0, "Invalid recorded byte length")
        require(re.fullmatch(r"[a-f0-9]{64}", record["sha256"]) is not None, "Invalid recorded SHA-256")
    targets = {record["path"]: record for record in records}
    require(len(targets) == len(records) and set(targets) == set(TARGETS), "Unexpected or duplicate omitted-data path")
    bindings = data["source_bindings"]
    require(set(bindings) == set(SOURCE_FILES), "Unexpected source/input bindings")
    for relative, record in bindings.items():
        require(matches(safe_path(ROOT, relative), record), "Frozen reconstruction source/input changed: " + relative)
    missing = []
    for relative in TARGETS:
        path = safe_path(ROOT, relative)
        if path.exists():
            require(matches(path, targets[relative]), "Existing recorded data differs; refusing overwrite: " + relative)
        else:
            missing.append(relative)
    return data, targets, missing


def reconstruct(stage: Path, missing: list[str], report: dict[str, Any]) -> dict[str, Path]:
    """Run only required frozen stages in new temporary output directories."""
    for relative in SOURCE_FILES:
        destination = safe_path(stage, relative)
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(safe_path(ROOT, relative), destination)
    generated: dict[str, Path] = {}
    commands: list[dict[str, Any]] = []
    report["generation"] = commands

    def command(label: str, arguments: list[str]) -> None:
        print("Reconstructing " + label + " from frozen recorded inputs...", file=sys.stderr, flush=True)
        started = time.perf_counter()
        completed = subprocess.run([sys.executable, *arguments], cwd=stage, capture_output=True, text=True, timeout=900)
        commands.append(
            {"stage": label, "elapsed_seconds": time.perf_counter() - started, "returncode": completed.returncode}
        )
        require(
            completed.returncode == 0, f"Frozen {label} reconstruction failed:\n{completed.stdout}\n{completed.stderr}"
        )

    def compare_to_recorded(temporary: Path, relative: str) -> None:
        require(
            sha(temporary) == sha(safe_path(ROOT, relative)), "Reconstructed companion metadata differs: " + relative
        )

    economic = stage / "economics"
    if "economics/results/development.json" in missing:
        output = stage / "generated/original-development"
        command(
            "original development search",
            [
                str(economic / "run_economics.py"),
                "freeze",
                "--pilot",
                str(economic / "results/pilot_input.json"),
                "--out",
                str(output),
            ],
        )
        compare_to_recorded(output / "FREEZE.json", "economics/results/FREEZE.json")
        compare_to_recorded(output / "pilot_input.json", "economics/results/pilot_input.json")
        generated["economics/results/development.json"] = output / "development.json"
    original_outputs = ("economics/results/confirmation.json", "economics/results/events.jsonl.gz")
    if any(name in missing for name in original_outputs):
        output = economic / "results"
        command(
            "original confirmation and event stream",
            [str(economic / "run_economics.py"), "confirm", "--out", str(output)],
        )
        compare_to_recorded(output / "summary.json", "economics/results/summary.json")
        compare_to_recorded(output / "CONFIRMATION_COMPLETE.json", "economics/results/CONFIRMATION_COMPLETE.json")
        generated.update({name: output / Path(name).name for name in original_outputs})
    elif any(name.startswith("economics/value_results/") for name in missing):
        shutil.copyfile(safe_path(ROOT, "economics/results/confirmation.json"), economic / "results/confirmation.json")
    value_outputs = ("economics/value_results/confirmation.json", "economics/value_results/events.jsonl.gz")
    if any(name in missing for name in value_outputs):
        output = economic / "value_results"
        command(
            "value-controller confirmation and event stream",
            [str(economic / "value_controller.py"), "confirm", "--out", str(output)],
        )
        compare_to_recorded(output / "summary.json", "economics/value_results/summary.json")
        compare_to_recorded(
            output / "VALUE_CONFIRMATION_COMPLETE.json", "economics/value_results/VALUE_CONFIRMATION_COMPLETE.json"
        )
        generated.update({name: output / Path(name).name for name in value_outputs})
    if "economics/prescreen_results/prescreen_confirmation.json" in missing:
        output = stage / "generated/prescreen"
        output.mkdir(parents=True)
        shutil.copyfile(economic / "prescreen_results/PRESCREEN_FREEZE.json", output / "PRESCREEN_FREEZE.json")
        command(
            "prospective prescreen confirmation",
            [str(economic / "prescreen_experiment.py"), "confirm", "--out", str(output)],
        )
        compare_to_recorded(output / "prescreen_summary.json", "economics/prescreen_results/prescreen_summary.json")
        generated["economics/prescreen_results/prescreen_confirmation.json"] = output / "prescreen_confirmation.json"
    if "opportunity/arrangement/results/conditional_frontier.json" in missing:
        output = stage / "generated/arrangement"
        source = stage / "opportunity/arrangement"
        command("finite arrangement search", [str(source / "checker.py"), "freeze", "--out", str(output)])
        compare_to_recorded(output / "FREEZE.json", "opportunity/arrangement/results/FREEZE.json")
        compare_to_recorded(
            output / "reference_selection.json", "opportunity/arrangement/results/reference_selection.json"
        )
        generated["opportunity/arrangement/results/conditional_frontier.json"] = output / "conditional_frontier.json"
    return generated


def run(check_only: bool = False) -> dict[str, Any]:
    """Verify or materialize only missing canonical artifacts, never replacements."""
    started = time.perf_counter()
    report: dict[str, Any] = {
        "schema": "recorded-data-materialization-report/v1",
        "edition": "2.1.0",
        "mode": "check" if check_only else "restore-absent-only",
        "python": sys.version,
        "zlib_compile_version": zlib.ZLIB_VERSION,
        "zlib_runtime_version": zlib.ZLIB_RUNTIME_VERSION,
        "installed": [],
        "network_calls": 0,
        "model_calls": 0,
        "replay_only": True,
    }
    try:
        require(not sys.flags.optimize, "Run without -O or PYTHONOPTIMIZE")
        data, targets, missing = verify_manifest()
        report.update(
            manifest_sha256=sha(MANIFEST),
            declared_files=len(targets),
            declared_bytes=sum(r["bytes"] for r in targets.values()),
            initially_missing=missing,
        )
        if not missing:
            report.update(passed=True, status="already complete; every recorded file matches; nothing written")
        elif check_only:
            report.update(passed=False, status="recorded data missing; rerun without --check to restore")
        else:
            # Staging is on the study filesystem so atomic hard-link installation
            # can never overwrite a destination. A different filesystem fails safe.
            with tempfile.TemporaryDirectory(prefix=".recorded-data-stage-", dir=ROOT / "packaging") as directory:
                stage = Path(directory)
                generated = reconstruct(stage, missing, report)
                for relative in missing:
                    require(relative in generated, "Missing reconstruction output: " + relative)
                    require(
                        matches(generated[relative], targets[relative]),
                        "Reconstruction is not byte-identical; nothing installed: " + relative,
                    )
                report["all_missing_bytes_verified_before_installation"] = True
                # Recheck the full destination set before installing the first file.
                for relative in TARGETS:
                    destination = safe_path(ROOT, relative)
                    if destination.exists():
                        require(
                            matches(destination, targets[relative]),
                            "Destination changed while reconstructing; refusing installation",
                        )
                for relative in missing:
                    destination = safe_path(ROOT, relative)
                    destination.parent.mkdir(parents=True, exist_ok=True)
                    try:
                        os.link(generated[relative], destination)
                    except FileExistsError:
                        require(
                            matches(destination, targets[relative]), "Concurrent destination differs; never overwritten"
                        )
                    else:
                        report["installed"].append(relative)
                for relative in TARGETS:
                    require(
                        matches(safe_path(ROOT, relative), targets[relative]),
                        "Installed data verification failed: " + relative,
                    )
            report.update(passed=True, status="missing recorded data restored exactly; existing evidence preserved")
        report["compression_reference"] = data["compression_reference"]
    except Exception as exc:
        report.update(passed=False, failure_type=type(exc).__name__, failure=str(exc))
    report["elapsed_seconds"] = time.perf_counter() - started
    return report


def main() -> None:
    """Print a machine-readable result and return nonzero on any mismatch."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Verify without reconstructing or writing; missing files fail the check."
    )
    args = parser.parse_args()
    report = run(args.check)
    print(json.dumps(report, indent=2, allow_nan=False))
    raise SystemExit(0 if report["passed"] else 1)


if __name__ == "__main__":
    main()
