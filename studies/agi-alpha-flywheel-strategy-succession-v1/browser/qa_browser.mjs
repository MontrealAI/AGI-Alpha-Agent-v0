import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath, pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {chromium, executablePath} from './qa-tools.mjs';

const root = path.dirname(fileURLToPath(import.meta.url));
const hashFile = async name => createHash('sha256').update(await fs.readFile(path.join(root, name))).digest('hex');
const testedArtifact = {html_sha256: await hashFile('index.html'), manifest: JSON.parse(await fs.readFile(path.join(root, 'BUNDLE_MANIFEST.json'), 'utf8'))};
const browser = await chromium.launch({executablePath, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage']});
const context = await browser.newContext({viewport: {width: 1440, height: 1100}, acceptDownloads: true, reducedMotion: 'reduce'});
const network = [];
await context.route(/^https?:/, route => { network.push(route.request().url()); return route.abort(); });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const checks = [];
const record = name => checks.push({name, passed: true});
try {
    await page.goto(pathToFileURL(path.join(root, 'index.html')).href);
    await page.waitForFunction(() => document.documentElement.dataset.ready === 'true', {timeout: 15000});
    record('Offline file booted with all module bytes checked');
    assert.equal(await page.locator('#empty-result').isVisible(), true);
    assert.equal(await page.locator('#plan-result').isVisible(), false);
    record('No precomputed result is presented before user start');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    record('Desktop has no horizontal overflow');
    await page.screenshot({path: path.join(root, 'screenshot-desktop-start.png'), fullPage: true});
    await page.click('#plan-button');
    await page.waitForFunction(() => !document.getElementById('plan-result').hidden || !document.getElementById('app-status').hidden);
    assert.equal(await page.locator('#plan-result').isVisible(), true, await page.locator('#app-status').textContent());
    assert.match(await page.locator('#result-badge').textContent(), /TARGET MET|TARGET MISSED/);
    assert.equal(await page.locator('#schedule-table tr').count(), 9);
    record('Fresh mission returns a checked nine-task schedule');
    await page.screenshot({path: path.join(root, 'screenshot-desktop-result.png'), fullPage: true});
    const downloadEvent = page.waitForEvent('download');
    await page.click('#download-plan');
    const download = await downloadEvent;
    const downloadPath = await download.path();
    const document = JSON.parse(await fs.readFile(downloadPath, 'utf8'));
    assert.equal(document.checker.valid, true);
    assert.equal(document.result.task_id, document.task.id);
    assert.deepEqual(document.result.proof, []);
    assert.deepEqual(document.result.authority, []);
    record('Download contains actual input-bound result and no inherited proof or authority');
    await page.fill('#deadline', '1');
    await page.click('#plan-button');
    await page.waitForFunction(() => document.getElementById('result-badge').textContent === 'TARGET MISSED');
    record('Impossible finish target is reported as missed, not accepted');
    await page.fill('input[data-job="J1"][data-field="deps"]', 'J9');
    await page.click('#plan-button');
    await page.waitForFunction(() => document.getElementById('app-status').textContent.includes('cycle'));
    assert.equal(await page.locator('#plan-result').isVisible(), false);
    record('Dependency cycle refuses the input and hides stale result');
    await page.click('#reset-example');
    await page.locator('#advanced-input summary').click();
    const forbidden = JSON.parse(await page.locator('#mission-json').inputValue());
    forbidden.authority = {scope: 'production'};
    await page.fill('#mission-json', JSON.stringify(forbidden));
    await page.click('#apply-json');
    await page.waitForFunction(() => document.getElementById('app-status').textContent.includes('outside this scope'));
    record('A supplied authority object is refused before execution');
    await page.click('#reset-example');
    await page.locator('#advanced-input summary').click();
    await page.click('#plan-button');
    await page.waitForSelector('#plan-result:not([hidden])');
    await page.locator('#tab-plan').focus();
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.getAttribute('#tab-stream', 'aria-selected'), 'true');
    record('Keyboard tab navigation works');
    await page.click('#tab-plan');
    await page.setViewportSize({width: 390, height: 844});
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({path: path.join(root, 'screenshot-mobile-result.png'), fullPage: true});
    record('Mobile has no horizontal page overflow and readable result');
    assert.deepEqual(errors, []);
    assert.deepEqual(network, []);
    assert.equal(await hashFile('index.html'), testedArtifact.html_sha256);
    record('No page errors and no network requests');
    const report = {schema: 'strategy-succession-browser-qa/v1', status: 'PASS', mode: 'file:// offline', checks, errors, network, browser: await browser.version(), tested_artifact: testedArtifact};
    await fs.writeFile(path.join(root, 'BROWSER_QA.json'), `${JSON.stringify(report, null, 2)}\n`);
    console.log(JSON.stringify(report));
} catch (error) {
    await page.screenshot({path: path.join(root, 'screenshot-qa-failure.png'), fullPage: true});
    const status = await page.locator('#app-status').textContent();
    await fs.writeFile(path.join(root, 'BROWSER_QA.json'), `${JSON.stringify({status: 'FAIL', checks, errors, network, error: error.message, app_status: status, tested_artifact: testedArtifact}, null, 2)}\n`);
    console.error(error);
    process.exitCode = 1;
} finally {
    await browser.close();
}
