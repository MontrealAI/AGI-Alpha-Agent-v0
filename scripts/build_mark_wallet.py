"""Build the wallet's pinned runtime digest profile without network access or signing."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

NAMES = {
    "Access": "AscensionAccess",
    "Seed": "NovaSeed",
    "Oracle": "AscensionRiskOracle",
    "Jobs": "AscensionJobMarket",
    "Mark": "AscensionMark",
}
ADDRESSES = {
    "Access": "0x36f8C079fEEBC81c5AF30D71be5017037246a32e",
    "Seed": "0xFA4737Ba7cF111EBb0840aA300BC61D84d303449",
    "Oracle": "0x06cb4D684628846B048d88CCf8C03c4Cfb74f149",
    "Jobs": "0x86f84E173A7a1a4588f4e757552F20f7C58e61E8",
    "Mark": "0xa28dA507f7F9AFF8910f1F7cB5d5b8238F5Db625",
}


def build(root: Path, docs: Path | None = None) -> Path:
    archive = root / "deployments/ethereum-mainnet/2026-10-11"
    manifest_bytes = (archive / "manifest.json").read_bytes()
    manifest = json.loads(manifest_bytes)
    runtimes = json.loads((archive / "runtime-code.json").read_text(encoding="utf-8"))
    if manifest["chainId"] != 1 or manifest["profile"] != "ascension-2026-10-11-solc-0.8.24":
        raise ValueError("Wrong deployment profile; do not substitute current-source artifacts")
    contracts = {}
    for alias, name in NAMES.items():
        record = manifest["contracts"][name]
        if record["address"].lower() != ADDRESSES[alias].lower():
            raise ValueError(f"{name}: changed deployment address")
        encoded = runtimes[name]
        if not isinstance(encoded, str) or not encoded.startswith("0x"):
            raise ValueError(f"{name}: invalid archived runtime")
        runtime = bytes.fromhex(encoded[2:])
        if not runtime or len(runtime) > 100000:
            raise ValueError(f"{name}: empty or oversized runtime")
        contracts[alias] = {
            "address": record["address"],
            "sha256": hashlib.sha256(runtime).hexdigest(),
            "archivedKeccak256": record["runtimeCodeHash"],
        }
        deployment = next((tx for tx in manifest.get("transactions", []) if tx.get("label") == f"Deploy {name}"), None)
        if deployment:
            if deployment.get("contractAddress", "").lower() != record["address"].lower() or not isinstance(
                deployment.get("blockNumber"), int
            ):
                raise ValueError(f"{name}: inconsistent archived deployment block")
            contracts[alias]["deploymentBlock"] = str(deployment["blockNumber"])
            contracts[alias]["deploymentBlockHash"] = deployment["blockHash"]
    output = {
        "schema": "agialpha.mark-wallet-profile.v1",
        "chainId": 1,
        "profile": manifest["profile"],
        "sourceManifestSHA256": hashlib.sha256(manifest_bytes).hexdigest(),
        "contracts": contracts,
        "newExposureEnabled": False,
        "reason": (
            "Archived deployment predates newer settlement safeguards; funding commissioning remains unresolved. "
            "No runtime override is accepted."
        ),
    }
    destination = (docs or root / "docs") / "assets/ascension-wallet/profile.json"
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(json.dumps(output, indent=2) + "\n", encoding="utf-8")
    return destination


def build_local_profile(root: Path, profile_path: Path, output_dir: Path) -> Path:
    """Create an isolated, build-bound exact-source local profile; never a Mainnet release."""
    root, output_dir = root.resolve(), output_dir.resolve()
    if output_dir == root or any(output_dir.is_relative_to(root / name) for name in ("docs", "site")):
        raise ValueError("Local acceptance profiles cannot be built into production source or Pages output")
    raw = profile_path.read_text(encoding="utf-8")
    if len(raw) > 100000:
        raise ValueError("Local profile exceeds the size limit")
    profile = json.loads(raw)
    if (
        profile.get("schema") != "agialpha.nova-local-profile.v1"
        or profile.get("chainId") not in (1337, 31337)
        or profile.get("environment") != "local-exact-source"
        or profile.get("mainnetQualification") is not False
        or profile.get("newExposureEnabled") is not True
    ):
        raise ValueError("Only explicitly local exact-source profiles may be generated by this builder")
    source = root / "docs/assets/ascension-wallet"
    result = subprocess.run(
        [
            "node",
            "--input-type=module",
            "-e",
            "const p=await import(process.argv[1]);"
            "process.stdout.write(JSON.stringify({identity:p.protocolIdentity(),actions:Object.keys(p.ACTIONS)}));",
            (source / "protocol.mjs").as_uri(),
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    protocol = json.loads(result.stdout)
    abi_digest = hashlib.sha256(protocol["identity"].encode("utf-8")).hexdigest()
    if profile.get("abiSHA256") != abi_digest or not re.fullmatch(r"[0-9a-f]{64}", profile.get("sourceSHA256", "")):
        raise ValueError("Local profile source or current browser ABI identity is missing or inconsistent")
    profile.setdefault("allowedActions", protocol["actions"])
    if (
        not isinstance(profile["allowedActions"], list)
        or any(action not in protocol["actions"] for action in profile["allowedActions"])
        or len(set(profile["allowedActions"])) != len(profile["allowedActions"])
    ):
        raise ValueError("Invalid local operation allowlist")
    for key in ("genesisHash", "deploymentBlockHash"):
        if not re.fullmatch(r"0x[0-9a-fA-F]{64}", profile.get(key, "")):
            raise ValueError(f"Missing pinned local {key}")
    if not re.fullmatch(r"0x(0|[1-9a-f][0-9a-f]*)", profile.get("deploymentBlock", "")):
        raise ValueError("Missing pinned deployment block")
    for alias in (*NAMES, "Token"):
        record = profile.get("contracts", {}).get(alias, {})
        if not re.fullmatch(r"0x[0-9a-fA-F]{40}", record.get("address", "")) or not re.fullmatch(
            r"[0-9a-f]{64}", record.get("sha256", "")
        ):
            raise ValueError(f"Missing pinned local {alias} address or runtime digest")
        if alias in ADDRESSES and record["address"].lower() == ADDRESSES[alias].lower():
            raise ValueError("Local profile cannot impersonate the archived Mainnet deployment")
    canonical = json.dumps(profile, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    entry = {"canonicalJSON": canonical, "sha256": hashlib.sha256(canonical.encode()).hexdigest(), "stage": "local"}
    output_dir.mkdir(parents=True, exist_ok=True)
    for name in ("client.mjs", "protocol.mjs", "recovery.mjs", "qualification.mjs"):
        shutil.copyfile(source / name, output_dir / name)
    (output_dir / "build-profile.mjs").write_text(
        "// SPDX-License-Identifier: Apache-2.0\n"
        "// GENERATED LOCAL ACCEPTANCE BUILD ONLY. Never publish as Mainnet qualification.\n"
        "export const BUILD_PROFILES = Object.freeze(" + json.dumps([entry], ensure_ascii=False) + ");\n",
        encoding="utf-8",
    )
    destination = output_dir / "profile.json"
    destination.write_text(json.dumps(profile, indent=2) + "\n", encoding="utf-8")
    return destination


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--docs-dir", type=Path)
    parser.add_argument("--local-profile", type=Path)
    parser.add_argument("--local-output", type=Path)
    args = parser.parse_args()
    if args.local_profile or args.local_output:
        if not args.local_profile or not args.local_output or args.docs_dir:
            parser.error("Use --local-profile and --local-output together, separately from --docs-dir")
        print(build_local_profile(args.root, args.local_profile, args.local_output))
    else:
        print(build(args.root, args.docs_dir))
